"""
提示词集合
==========

集中管理研究 Agent 各环节的提示词，便于统一调优。每个提示词都明确：
角色、任务、输出格式（固定 Markdown 小标题，保证结果稳定可读）。

环节：
- 相关性筛选 SCREEN
- 单篇精读归纳 DIGEST
- 创新点 / idea 提炼 IDEA
- PDF 全文精读 PDF_DIGEST
"""

from __future__ import annotations

SYSTEM_RESEARCHER = (
    "你是一位资深的计算机科学研究员，擅长快速阅读论文、把握方法本质，"
    "并能从多篇工作的对比中发现研究空白与可落地的创新点。"
    "你的回答要具体、有依据，不堆砌空话，所有结论尽量对应到具体论文。"
)

# 1) 相关性筛选：从候选论文中挑出与主题真正相关的
SCREEN_PROMPT = """我会给你研究主题和一批候选论文（含 ID、标题、摘要）。
请判断哪些与主题高度相关、值得精读。

研究主题：{topic}

候选论文：
{candidates}

请按下面格式输出，每行一个值得保留的论文 ID（不要输出其他内容）：
KEEP: 论文ID
KEEP: 论文ID
若全部不相关，输出：NONE"""

# 2) 单篇精读归纳（基于摘要或全文）
DIGEST_PROMPT = """请精读以下论文，并用固定结构输出中文分析。

论文信息：
{paper}

请按这些小标题输出：
### 研究问题
（它要解决什么问题）
### 核心方法
（用了什么思路/技术，关键机制）
### 主要创新
（相比已有工作的新东西）
### 局限与不足
（方法的边界、未解决的问题）
### 可借鉴点
（能迁移到其他场景的设计）"""

# 3) 创新点 / idea 提炼（基于多篇归纳做横向对比）
IDEA_PROMPT = """下面是围绕主题"{topic}"的若干篇论文精读笔记。
请横向对比这些工作，找出可落地的研究创新点和 idea。

精读笔记：
{digests}

请按以下结构输出：
## 一、研究现状与共性
（这些工作共同的思路、共同的局限）
## 二、研究空白
（目前没人做、或做得不好的方向，至少 3 条）
## 三、候选创新点 / Idea
（每条包含：idea 名称、具体做法、为什么可行、可结合的论文/技术、预期难点）
至少给出 4 条，按可行性排序。
## 四、推荐的下一步
（验证这些 idea 可以先做的最小实验）"""

# 4) PDF 全文精读（分块后对每块/整体做笔记）
PDF_DIGEST_PROMPT = """请精读以下论文全文片段，产出结构化阅读笔记。
论文标题：{title}

全文内容：
{content}

请按这些小标题输出：
### 论文概述
### 问题与动机
### 方法详解
### 实验与结论
### 创新点
### 局限与可改进方向"""

# 5) 基于一篇或多篇 PDF 笔记提炼 idea
PDF_IDEA_PROMPT = """基于以下论文精读笔记，帮我提炼可做的创新点和 idea。

笔记：
{notes}

请输出：
## 可延展的方向（至少 3 条）
## 具体 Idea（每条含做法、依据、难点，至少 3 条）
## 与现有工作的差异化"""
